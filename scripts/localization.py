#!/usr/bin/env python3
"""Build/check Isekai-only localization data and conservative source inventory."""
import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re
import subprocess
from source_catalog import resolve

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'localization/ko-kr.json'
DATA = ROOT / 'IsekaiMod/Localization/KoreanTranslationData.cs'
AUDIT = ROOT / 'localization/source-audit.json'

def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))

def tokens(text):
    # Tokens are compared, not stripped or rewritten. Link targets and variables stay opaque.
    return Counter(re.findall(r'\{[^{}]*\}|<[^<>]*>', text))

def validate_nesting(text):
    stack = []
    for token in re.findall(r'\{[^{}]*\}|<[^<>]*>', text):
        if token.startswith('{g|') or token == '{n}':
            stack.append('g' if token.startswith('{g|') else 'n')
        elif token in ('{/g}', '{/n}'):
            kind = token[2:-1]
            if not stack or stack.pop() != kind:
                raise ValueError('Unbalanced localization markup')
        elif re.fullmatch(r'<(?:b|i|color|link|size)(?:=[^<>]*)?>', token):
            stack.append(token[1:].split('=')[0].rstrip('>'))
        elif re.fullmatch(r'</(?:b|i|color|link|size)>', token):
            if not stack or stack.pop() != token[2:-1]:
                raise ValueError('Unbalanced rich text')
    if stack:
        raise ValueError('Unclosed markup')

def validate(catalog, constants):
    identities = set()
    for row in catalog['Entries']:
        identity = (row['Key'], row['English'], row['ProcessTemplates'])
        if identity in identities:
            raise ValueError('Duplicate catalog identity: ' + str(identity))
        identities.add(identity)
        if row['Key'] is not None and not re.fullmatch('[a-f0-9]{32}', row['Key']):
            raise ValueError('Invalid key')
        if type(row['ProcessTemplates']) is not bool:
            raise ValueError('Invalid template flag')
        if row['English'] not in constants:
            raise ValueError('English no longer present in source: ' + row['SimpleName'])
        invariant = row['Korean'] == row['English'] and not re.search(r'[A-Za-z가-힣]', row['English'])
        if not row['Korean'].strip() or (not re.search('[가-힣]', row['Korean']) and not invariant):
            raise ValueError('Missing Korean: ' + row['SimpleName'])
        if tokens(row['English']) != tokens(row['Korean']):
            raise ValueError('Changed markup/variables: ' + row['SimpleName'])
        validate_nesting(row['Korean'])
        if not row.get('Evidence'):
            raise ValueError('Missing review evidence')
    for en, ko in catalog['UI'].items():
        validate_nesting(ko)
        if tokens(en) != tokens(ko) or not re.search('[가-힣]', ko):
            raise ValueError('Invalid UI translation: ' + en)

def render(catalog):
    def literal(s):
        return json.dumps(s, ensure_ascii=False).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    lines = ['// Generated by scripts/localization.py. Do not edit.',
             'namespace IsekaiMod.Localization {', '  internal static class KoreanTranslationData {',
             '    internal static void Register() {']
    for r in catalog['Entries']:
        lines.append('      KoreanLocalization.Add(' + ', '.join(literal(r[k]) for k in ('Key','English','Korean')) + ', ' + str(r['ProcessTemplates']).lower() + ');')
    for en, ko in sorted(catalog['UI'].items()):
        lines.append('      KoreanLocalization.UIStrings.Add(' + literal(en) + ', ' + literal(ko) + ');')
    return '\n'.join(lines + ['    }', '  }', '}']) + '\n'

def inventory():
    subprocess.run([str(ROOT/'scripts/dotnet.sh'), 'build', str(ROOT/'scripts/LocalizationInventory'), '--nologo', '-v:q'], check=True, stdout=subprocess.DEVNULL)
    result = subprocess.run([str(ROOT/'scripts/dotnet.sh'), str(ROOT/'scripts/LocalizationInventory/bin/Debug/net8.0/LocalizationInventory.dll'), str(ROOT)], capture_output=True, text=True, check=True)
    return json.loads(result.stdout)

def target_catalog(source):
    return resolve(source, read(ROOT/'IsekaiMod/Localization/LocalizationPack.json')['LocalizedStrings'])

def coverage(catalog, targets):
    expected={(r['English'], r['ProcessTemplates']) for r in targets}
    actual={(r['English'], r['ProcessTemplates']) for r in catalog['Entries']}
    if expected != actual:
        raise ValueError(f'Coverage mismatch: missing={expected-actual}; unsupported={actual-expected}')

def audit(source, catalog):
    targets=target_catalog(source)
    identities={(r['English'],r['ProcessTemplates']):r for r in catalog['Entries']}
    excluded=read(ROOT/'localization/obsolete-entries.json')['Entries']
    obsolete={r['Key']:r for r in excluded}
    current={(r['English'],r['ProcessTemplates']) for r in targets}
    pack=read(ROOT/'IsekaiMod/Localization/LocalizationPack.json')['LocalizedStrings']
    rows=[]
    for row in pack:
        identity=(row['enGB'],row['ProcessTemplates'])
        if identity in current:
            status='translated-current-source' if identity in identities else 'missing-translation'
        elif row['Key'] in obsolete:
            status='obsolete-reviewed'
        else:
            raise ValueError('Unclassified pack entry: '+row['SimpleName'])
        rows.append(dict(Key=row['Key'],SimpleName=row['SimpleName'],Status=status))
    for row in targets:row['Translated']=(row['English'],row['ProcessTemplates']) in identities
    return dict(SchemaVersion=2,Baseline='e4d5ac3bf57c9b644fe5d1000e69a5a6ed1a26df',
                Boundary='Static source and bounded wrapper reconstruction, including optional branches; not observed Unity runtime registration.',
                PackSHA256=hashlib.sha256((ROOT/'IsekaiMod/Localization/LocalizationPack.json').read_bytes()).hexdigest(),
                PackCount=len(pack),TranslationCount=len(catalog['Entries']),UICount=len(catalog['UI']),
                TargetCount=len(targets),PackEntries=rows,Targets=targets,Calls=source['Calls'],Factories=source['Factories'])

def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check', action='store_true'); args=parser.parse_args()
    source=inventory(); catalog=read(CATALOG)
    if source["SyntaxErrors"]: raise ValueError("C# syntax errors: "+str(source["SyntaxErrors"]))
    targets=target_catalog(source)
    validate(catalog, {r['English'] for r in targets})
    coverage(catalog, targets)
    outputs={DATA:render(catalog), ROOT/'localization/runtime-targets.json':json.dumps(targets, ensure_ascii=False, indent=2)+'\n', AUDIT:json.dumps(audit(source,catalog), ensure_ascii=False, indent=2)+'\n'}
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise ValueError('Stale generated file: '+str(path))
        else: path.write_text(expected)
    print(f"PASS: {len(catalog['Entries'])} source-checked translations; {len(catalog['UI'])} UI/messages; {len(source['Calls'])} calls inventoried")
if __name__ == '__main__': main()
